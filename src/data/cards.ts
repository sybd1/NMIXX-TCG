export const getCardById = (id: string): Card | undefined => {
  return MASTER_CARDS.find(card => card.id === id);
};

export const getCardsByMember = (member: string): Card[] => {
  if (member === 'ALL') return MASTER_CARDS;
  return MASTER_CARDS.filter(card => card.member === member);
};

export const getCardsByRarity = (rarity: string): Card[] => {
  if (rarity === 'ALL') return MASTER_CARDS;
  return MASTER_CARDS.filter(card => card.rarity === rarity);
};
